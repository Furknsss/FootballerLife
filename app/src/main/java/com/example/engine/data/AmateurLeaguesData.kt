    private fun buildAmateurSquad(
        clubId: String,
        strength: Int,
        starName: String,
        starOvr: Int,
        starPos: Position,
        starNum: Int
    ): List<SquadMemberInfo> {
        val baseNames = listOf(
            Pair("Ahmet", "Yılmaz"), Pair("Mehmet", "Demir"), Pair("Mustafa", "Kaya"),
            Pair("Ali", "Çelik"), Pair("Hüseyin", "Şahin"), Pair("İsmail", "Öztürk"),
            Pair("Murat", "Arslan"), Pair("Emre", "Aydın"), Pair("Burak", "Koç"),
            Pair("Furkan", "Doğan"), Pair("Kadir", "Kurt")
        )
        val positions = listOf(
            Position.GK, Position.FB, Position.CB, Position.CB, Position.FB,
            Position.DM, Position.CM, Position.WG, Position.AM, Position.WG, Position.ST
        )
        val numbers = listOf(1, 2, 4, 5, 3, 6, 8, 7, 10, 11, 9)
        val hash = clubId.hashCode().let { if (it < 0) -it else it }

        val list = mutableListOf<SquadMemberInfo>()
        list.add(
            SquadMemberInfo(
                id = "${clubId}_STAR",
                name = starName,
                position = starPos,
                kitNumber = starNum,
                overall = starOvr,
                age = 24 + (hash % 10),
                isCaptain = true
            )
        )

        positions.forEachIndexed { i, pos ->
            if (pos != starPos || list.size < 2) {
                val pair = baseNames[(hash + i) % baseNames.size]
                val ovr = (strength - 2 + (i % 4)).coerceIn(35, 48)
                val kit = numbers[i]
                if (kit != starNum && list.none { it.kitNumber == kit }) {
                    list.add(
                        SquadMemberInfo(
                            id = "${clubId}_P$i",
                            name = "${pair.first} ${pair.second}",
                            position = pos,
                            kitNumber = kit,
                            overall = ovr,
                            age = 19 + ((hash + i) % 15)
                        )
                    )
                }
            }
        }
        return list.take(11)
    }
